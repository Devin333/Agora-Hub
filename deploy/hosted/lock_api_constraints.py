"""Write the API image's pip constraints from a tested environment.

The hosted API image installs the project with its ``api`` and ``rerank`` extras. Its dependency ranges
are open in ``pyproject.toml``; the image pins the exact versions of the whole
closure that the project's test environment resolved, so a rebuild months later
installs what was tested rather than whatever is newest.

Run with the project's virtual environment interpreter from the repository root:

    .venv/Scripts/python.exe deploy/hosted/lock_api_constraints.py

Packages the closure needs only on another platform (for example ``uvloop`` on
Linux) are not installed in a Windows environment and therefore stay unpinned;
pip resolves them inside the image.
"""

from __future__ import annotations

import argparse
import re
import tomllib
from collections.abc import Iterable
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

PYPROJECT = Path(__file__).resolve().parents[2] / "pyproject.toml"
ROOT_EXTRAS = ("api", "rerank")
# The image is Linux x86_64 on CPython 3.12; markers are evaluated for it, not for the host.
TARGET_ENVIRONMENT = {
    **default_environment(),
    "sys_platform": "linux",
    "platform_system": "Linux",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "python_version": "3.12",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
}
DEFAULT_OUTPUT = Path(__file__).with_name("api-constraints.txt")


def root_requirements(pyproject: Path, extras: Iterable[str]) -> list[Requirement]:
    """The image's direct requirements: the project's dependencies plus the chosen extras."""

    project = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]
    optional = project.get("optional-dependencies", {})
    raw = list(project.get("dependencies", ()))
    for extra in extras:
        if extra not in optional:
            raise SystemExit(f"pyproject.toml has no optional dependency group {extra!r}")
        raw.extend(optional[extra])
    return [Requirement(item) for item in raw]


def _applies(requirement: Requirement, active_extras: frozenset[str]) -> bool:
    if requirement.marker is None:
        return True
    return any(
        requirement.marker.evaluate({**TARGET_ENVIRONMENT, "extra": extra})
        for extra in (active_extras or {""})
    )


def closure(requirements: Iterable[Requirement]) -> tuple[dict[str, str], list[str]]:
    """Installed versions of every distribution the requirements reach on the target."""

    pinned: dict[str, str] = {}
    missing: list[str] = []
    pending = [
        (requirement.name, frozenset(requirement.extras))
        for requirement in requirements
        if _applies(requirement, frozenset())
    ]
    roots = {canonicalize_name(name) for name, _ in pending}
    seen: set[tuple[str, frozenset[str]]] = set()
    while pending:
        name, active_extras = pending.pop()
        key = (canonicalize_name(name), active_extras)
        if key in seen:
            continue
        seen.add(key)
        try:
            distribution = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            if key[0] in roots:
                missing.append(key[0])
            continue
        pinned[canonicalize_name(distribution.metadata["Name"])] = distribution.version
        for raw in distribution.requires or ():
            requirement = Requirement(raw)
            if _applies(requirement, active_extras):
                pending.append((requirement.name, frozenset(requirement.extras)))
    return pinned, sorted(set(missing))


def render(pinned: dict[str, str]) -> str:
    lines = [
        "# Generated by deploy/hosted/lock_api_constraints.py from the tested environment.",
        "# Do not edit by hand; regenerate after changing dependencies.",
    ]
    for name in sorted(pinned):
        # A local version label ("+cpu", "+cu128") names the wheel index a build came
        # from, not the release. The image installs torch from the CPU index first, and
        # a public ``==`` pin matches any local label, so the label is dropped.
        version = re.sub(r"\+.*$", "", pinned[name])
        lines.append(f"{name}=={version}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    pinned, missing = closure(root_requirements(PYPROJECT, ROOT_EXTRAS))
    if missing:
        raise SystemExit(
            "direct requirements are not installed in this interpreter: " + ", ".join(missing)
        )
    args.output.write_text(render(pinned), encoding="utf-8")
    print(f"wrote {len(pinned)} pins to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
